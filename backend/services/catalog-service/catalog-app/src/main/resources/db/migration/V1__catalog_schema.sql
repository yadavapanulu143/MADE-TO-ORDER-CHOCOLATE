-- Catalog service schema.
--
-- Owned exclusively by the catalog service. No other service reads or writes these tables; the order
-- service keeps its own copy of a variant's price at purchase time and never joins here.
--
-- Every monetary column is a BIGINT count of paise. No column is a floating-point type, so a stored
-- price is exact and re-reading it cannot drift; this is what lets the order service trust a
-- historical price without re-deriving it.

CREATE TABLE products (
    id               UUID         PRIMARY KEY,
    -- Public address. Immutable once set: it is the product's URL, and rewriting it would break
    -- every link and bookmark a customer holds.
    slug             VARCHAR(80)  NOT NULL,
    name             VARCHAR(150) NOT NULL,
    short_description VARCHAR(500),
    description      TEXT,
    preparation_info TEXT,
    delivery_info    TEXT,
    status           VARCHAR(16)  NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    -- Optimistic locking: two administrators editing one product must not silently overwrite.
    version          BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT products_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT products_slug_not_blank CHECK (length(trim(slug)) > 0),
    CONSTRAINT products_status_valid CHECK (status IN ('DRAFT', 'PUBLISHED', 'UNPUBLISHED', 'ARCHIVED'))
);

-- The slug is the storefront lookup key, so it is unique across every status. A product that is
-- unpublished still holds its address, so a later product cannot take it and shadow the original.
CREATE UNIQUE INDEX products_slug_unique ON products (slug);

-- The storefront lists published products; a partial index keeps that scan off the drafts and the
-- archive, which an administrator browses far less often.
CREATE INDEX products_published ON products (created_at DESC) WHERE status = 'PUBLISHED';
CREATE INDEX products_status ON products (status, created_at DESC);

CREATE TABLE product_variants (
    id                 UUID        PRIMARY KEY,
    product_id         UUID        NOT NULL,
    label              VARCHAR(80) NOT NULL,
    sku                VARCHAR(64),
    -- Price in paise. Integer, never a floating-point type.
    price_minor_units  BIGINT      NOT NULL,
    currency           VARCHAR(3)  NOT NULL DEFAULT 'INR',
    min_order_quantity INTEGER     NOT NULL DEFAULT 1,
    max_order_quantity INTEGER     NOT NULL DEFAULT 10,
    active             BOOLEAN     NOT NULL DEFAULT TRUE,
    display_order      INTEGER     NOT NULL DEFAULT 0,

    CONSTRAINT product_variants_product_fk
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT product_variants_label_not_blank CHECK (length(trim(label)) > 0),
    CONSTRAINT product_variants_price_positive CHECK (price_minor_units > 0),
    CONSTRAINT product_variants_quantity_bounds CHECK (
        min_order_quantity >= 1 AND max_order_quantity >= min_order_quantity)
);

CREATE INDEX product_variants_product ON product_variants (product_id);
-- A SKU identifies one variant across the catalogue; nulls (no SKU) are not compared, so many
-- variants may omit it.
CREATE UNIQUE INDEX product_variants_sku_unique ON product_variants (sku) WHERE sku IS NOT NULL;

CREATE TABLE product_images (
    id            UUID         PRIMARY KEY,
    product_id    UUID         NOT NULL,
    -- Opaque key generated by the service. Never a caller-supplied path, so a row cannot be read to
    -- learn where content physically lives.
    storage_key   VARCHAR(120) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    alt_text      VARCHAR(200),
    display_order INTEGER      NOT NULL DEFAULT 0,
    is_primary    BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT product_images_product_fk
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT product_images_key_not_blank CHECK (length(trim(storage_key)) > 0),
    CONSTRAINT product_images_size_positive CHECK (size_bytes > 0)
);

CREATE INDEX product_images_product ON product_images (product_id);
-- At most one primary image per product. Enforced by the database, not only by the aggregate, so a
-- second primary cannot appear through any path.
CREATE UNIQUE INDEX product_images_one_primary
    ON product_images (product_id) WHERE is_primary;

CREATE TABLE product_attributes (
    id            UUID         PRIMARY KEY,
    product_id    UUID         NOT NULL,
    name          VARCHAR(60)  NOT NULL,
    value         VARCHAR(300) NOT NULL,
    display_order INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT product_attributes_product_fk
        FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT product_attributes_name_not_blank CHECK (length(trim(name)) > 0),
    -- An attribute name is unique within a product, so the same specification cannot be listed twice
    -- with different values.
    CONSTRAINT product_attributes_name_unique UNIQUE (product_id, name)
);

CREATE INDEX product_attributes_product ON product_attributes (product_id);

-- The single website-settings row. A fixed all-zeroes id marks it unmistakably as the singleton.
CREATE TABLE website_settings (
    id                   UUID         PRIMARY KEY,
    seller_name          VARCHAR(150),
    contact_email        VARCHAR(254),
    contact_phone        VARCHAR(20),
    contact_address      TEXT,
    privacy_policy       TEXT,
    terms_and_conditions TEXT,
    shipping_policy      TEXT,
    refund_policy        TEXT,
    updated_at           TIMESTAMPTZ  NOT NULL
);

-- Transactional outbox, shared shape across every service. The relay publishes rows after the
-- business transaction commits, so a broker outage delays events without losing them.
-- Table name and columns must match com.choco.events.outbox.OutboxEvent.
CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    event_type     VARCHAR(120) NOT NULL,
    aggregate_id   VARCHAR(120) NOT NULL,
    schema_version INTEGER      NOT NULL DEFAULT 1,
    payload        TEXT         NOT NULL,
    correlation_id VARCHAR(120),
    occurred_at    TIMESTAMPTZ  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INTEGER      NOT NULL DEFAULT 0,
    last_error     VARCHAR(500)
);

-- The relay scans unpublished rows oldest first; a partial index keeps that scan off the published
-- history, which grows without bound.
CREATE INDEX idx_outbox_unpublished
    ON outbox_event (created_at)
    WHERE published_at IS NULL;

-- Catalog audit trail. A separate table from the identity service's, because each service owns its
-- data; a change to a product's price is recorded here and never written into another service's log.
CREATE TABLE audit_log (
    id             BIGSERIAL    PRIMARY KEY,
    occurred_at    TIMESTAMPTZ  NOT NULL,
    actor_type     VARCHAR(32)  NOT NULL,
    actor_id       VARCHAR(64),
    action         VARCHAR(64)  NOT NULL,
    target_type    VARCHAR(32),
    target_id      VARCHAR(64),
    outcome        VARCHAR(16)  NOT NULL,
    detail         VARCHAR(512),
    correlation_id VARCHAR(64)
);

CREATE INDEX catalog_audit_log_occurred_at ON audit_log (occurred_at DESC);
CREATE INDEX catalog_audit_log_actor ON audit_log (actor_type, actor_id, occurred_at DESC);
CREATE INDEX catalog_audit_log_action ON audit_log (action, occurred_at DESC);
